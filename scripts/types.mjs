// Makes dashboard/src/api-types.ts from the backend's OpenAPI document, so the
// dashboard's types cannot drift from the API's models.
// `npm run types` writes it, and `npm run types:check` fails if it is out of date.
import { readFileSync, writeFileSync } from "node:fs";
import { format } from "prettier";

const output = "dashboard/src/api-types.ts";

const document = JSON.parse(readFileSync("dashboard/openapi.json", "utf8"));

const PRIMITIVES = {
  string: "string",
  number: "number",
  integer: "number",
  boolean: "boolean",
  null: "null",
};

const literal = (value) => JSON.stringify(value);

/** The TypeScript for one property of a schema. `alias` names an enum it holds. */
function typeOf(schema, alias, aliases) {
  if (schema.$ref) return schema.$ref.split("/").at(-1);
  if (schema.enum) {
    aliases.set(alias, schema.enum.map(literal).join(" | "));
    return alias;
  }
  if (schema.const !== undefined) return literal(schema.const);
  if (schema.anyOf) {
    return schema.anyOf.map((part) => typeOf(part, alias, aliases)).join(" | ");
  }
  if (schema.type === "array")
    return `${typeOf(schema.items, alias, aliases)}[]`;
  if (schema.type === "object") return "Record<string, unknown>";
  return PRIMITIVES[schema.type];
}

const capital = (word) => word.charAt(0).toUpperCase() + word.slice(1);

function declare(name, schema, aliases) {
  if (schema.enum)
    return `export type ${name} = ${schema.enum.map(literal).join(" | ")};`;
  const required = new Set(schema.required ?? []);
  const fields = Object.entries(schema.properties ?? {}).map(
    ([key, property]) => {
      const alias = `${name}${key.split("_").map(capital).join("")}`;
      const mark = required.has(key) ? "" : "?";
      return `  ${key}${mark}: ${typeOf(property, alias, aliases)};`;
    },
  );
  return `export interface ${name} {\n${fields.join("\n")}\n}`;
}

const aliases = new Map();
const declarations = Object.entries(document.components.schemas).map(
  ([name, schema]) => declare(name, schema, aliases),
);
const types = [...aliases].map(
  ([name, union]) => `export type ${name} = ${union};`,
);

const generated = await format(
  [
    "// Generated by scripts/types.mjs from the backend's OpenAPI document. Do not edit.",
    "// Run `npm run types` after changing backend/models.py.",
    ...types,
    ...declarations,
  ].join("\n\n"),
  { parser: "typescript" },
);

if (process.argv.includes("--check")) {
  if (readFileSync(output, "utf8") !== generated) {
    console.error(`${output} is out of date. Run: npm run types`);
    process.exit(1);
  }
} else {
  writeFileSync(output, generated);
}
