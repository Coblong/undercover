// Makes the dashboard's API types from the backend's OpenAPI document, so they
// cannot drift from the API's models. `dashboard/src/api-types.ts` re-exports the
// parts, which are kept under the line limit (`api-types-1.ts`, `api-types-2.ts`...).
// `npm run types` writes them, and `npm run types:check` fails if they are out of date.
import { readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { format } from "prettier";

const folder = "dashboard/src";
const barrel = `${folder}/api-types.ts`;
const MAX_LINES = 400;

const document = JSON.parse(readFileSync("dashboard/openapi.json", "utf8"));

const PRIMITIVES = {
  string: "string",
  number: "number",
  integer: "number",
  boolean: "boolean",
  null: "null",
};

const literal = (value) => JSON.stringify(value);

/** The TypeScript for one property of a schema. `alias` names an enum it holds. */
function typeOf(schema, alias, aliases, refs) {
  if (schema.$ref) {
    const name = schema.$ref.split("/").at(-1);
    refs.add(name);
    return name;
  }
  if (schema.enum) {
    aliases.set(alias, schema.enum.map(literal).join(" | "));
    return alias;
  }
  if (schema.const !== undefined) return literal(schema.const);
  if (schema.anyOf) {
    return schema.anyOf
      .map((part) => typeOf(part, alias, aliases, refs))
      .join(" | ");
  }
  if (schema.type === "array")
    return `${typeOf(schema.items, alias, aliases, refs)}[]`;
  if (schema.type === "object") return "Record<string, unknown>";
  return PRIMITIVES[schema.type];
}

const capital = (word) => word.charAt(0).toUpperCase() + word.slice(1);

/** One schema as TypeScript: the aliases it needs, then the declaration, and what it refers to. */
function declare(name, schema) {
  const aliases = new Map();
  const refs = new Set();
  let declaration;
  if (schema.enum) {
    declaration = `export type ${name} = ${schema.enum.map(literal).join(" | ")};`;
  } else {
    const required = new Set(schema.required ?? []);
    const fields = Object.entries(schema.properties ?? {}).map(
      ([key, property]) => {
        const alias = `${name}${key.split("_").map(capital).join("")}`;
        const mark = required.has(key) ? "" : "?";
        return `  ${key}${mark}: ${typeOf(property, alias, aliases, refs)};`;
      },
    );
    declaration = `export interface ${name} {\n${fields.join("\n")}\n}`;
  }
  const text = [
    ...[...aliases].map(([alias, union]) => `export type ${alias} = ${union};`),
    declaration,
  ].join("\n\n");
  refs.delete(name);
  return { name, text, refs, lines: text.split("\n").length };
}

// Fill each part up to the line limit, in the order the API lists its models.
const parts = [[]];
let lines = 0;
for (const [name, schema] of Object.entries(document.components.schemas)) {
  const declared = declare(name, schema);
  if (lines + declared.lines > MAX_LINES) {
    parts.push([]);
    lines = 0;
  }
  parts.at(-1).push(declared);
  lines += declared.lines;
}

const owner = new Map();
parts.forEach((part, index) => {
  for (const { name } of part) owner.set(name, index + 1);
});

const BANNER = [
  "// Generated by scripts/types.mjs from the backend's OpenAPI document. Do not edit.",
  "// Run `npm run types` after changing backend/models.py.",
];

const files = new Map();
for (const [index, part] of parts.entries()) {
  const here = index + 1;
  const imports = new Map();
  for (const { refs } of part) {
    for (const ref of refs) {
      const from = owner.get(ref);
      if (from !== here) imports.set(from, [...(imports.get(from) ?? []), ref]);
    }
  }
  const lines = [...imports]
    .toSorted(([a], [b]) => a - b)
    .map(
      ([from, names]) =>
        `import type { ${[...new Set(names)].toSorted().join(", ")} } from "./api-types-${String(from)}";`,
    );
  files.set(
    `${folder}/api-types-${String(here)}.ts`,
    [...BANNER, ...lines, ...part.map(({ text }) => text)].join("\n\n"),
  );
}
files.set(
  barrel,
  [
    ...BANNER,
    ...parts.map(
      (_, index) => `export * from "./api-types-${String(index + 1)}";`,
    ),
  ].join("\n\n"),
);

const generated = new Map();
for (const [path, text] of files) {
  generated.set(path, await format(text, { parser: "typescript" }));
}

const stale = readdirSync(folder)
  .filter((name) => /^api-types-\d+\.ts$/.test(name))
  .map((name) => `${folder}/${name}`)
  .filter((path) => !generated.has(path));

if (process.argv.includes("--check")) {
  const behind = [...generated].filter(([path, text]) => {
    try {
      return readFileSync(path, "utf8") !== text;
    } catch {
      return true;
    }
  });
  if (behind.length > 0 || stale.length > 0) {
    console.error("The API types are out of date. Run: npm run types");
    process.exit(1);
  }
} else {
  for (const path of stale) rmSync(path);
  for (const [path, text] of generated) writeFileSync(path, text);
}
